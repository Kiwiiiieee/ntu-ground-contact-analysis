# ----------------------------------------------------------------------------- inter-pass gaps
def run_gaps_h(report_name: str) -> np.ndarray:
    """Gaps between consecutive passes that touch the window (parse_contacts definition)."""
    w = window_passes(report_name)
    return (w.t0.values[1:] - w.t1.values[:-1]) / 3600.0


