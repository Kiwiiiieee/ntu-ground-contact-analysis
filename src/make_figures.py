def fig_elevation_masks() -> None:
    orbit = "h500_i45_raan0"
    st = gmat_states(orbit)
    t, el = st["Sat.ElapsedSecs"].values, elevation_deg(st)
    t_lo = C.WINDOW_OFFSET_H * 3600
    day = (t >= t_lo) & (t <= t_lo + 24 * 3600)
    p10, p5 = window_passes(f"{orbit}_el{MASK:g}"), window_passes(f"{orbit}_el{C.MIN_ELEVATION_SENSITIVITY_DEG:g}")
    first = p5[p5.t0 >= t_lo].iloc[0]
    fig, (a, b) = plt.subplots(1, 2, figsize=(7.0, 2.6), gridspec_kw={"width_ratios": [2, 1]})
    for ax, sel in ((a, day), (b, (t >= first.t0 - 600) & (t <= first.t1 + 600))):
        x = (t[sel] - t_lo) / 3600
        ax.plot(x, el[sel], color=CATEGORICAL[0], linewidth=1)
        for mask, col, passes in ((MASK, CATEGORICAL[1], p10), (C.MIN_ELEVATION_SENSITIVITY_DEG, CATEGORICAL[2], p5)):
            ax.axhline(mask, color=col, linewidth=1, label=f"{mask:g}° mask")
            for p in passes.itertuples():
                ax.axvspan((p.t0 - t_lo) / 3600, (p.t1 - t_lo) / 3600, color=col, alpha=0.12, linewidth=0)
        ax.set_xlim(x.min(), x.max())
        ax.set_ylabel("Elevation at NTU (°)")
        ax.set_xlabel("Hours since window start")
    a.set_ylim(-90, 90)
    b.set_ylim(0, max(el[(t >= first.t0) & (t <= first.t1)]) + 5)
    a.set_title("500 km, 45°, RAAN 0°: first 24 h; shaded = GMAT-reported passes", loc="left", color=INK_2)
    b.set_title("one pass: the 5° pass contains the 10° pass", loc="left", color=INK_2)
    a.legend(loc="upper left", fontsize=6.5)
    fig.tight_layout()
    save(fig, "fig_elevation_masks")


