# ----------------------------------------------------------------------------- ground tracks
def visibility_circle(mean_alt_km: float, mask_deg: float, n: int = 361):
    """Sub-satellite points for which NTU sees the satellite above the mask:
    Earth central half-angle lambda = acos(R cos(el) / r) - el (spherical Earth)."""
    el = math.radians(mask_deg)
    lam = math.acos(C.R_EQ_KM * math.cos(el) / (C.R_EQ_KM + mean_alt_km)) - el
    phi, lon0 = math.radians(C.STATION_LAT_DEG), math.radians(C.STATION_LON_DEG)
    th = np.linspace(0, 2 * np.pi, n)
    lat = np.arcsin(np.sin(phi) * np.cos(lam) + np.cos(phi) * np.sin(lam) * np.cos(th))
    lon = lon0 + np.arctan2(np.sin(th) * np.sin(lam) * np.cos(phi), np.cos(lam) - np.sin(phi) * np.sin(lat))
    return np.degrees(lon), np.degrees(lat), math.degrees(lam)


def track_with_breaks(lon, lat):
    lon = ((np.asarray(lon, float) + 180.0) % 360.0) - 180.0
    lat = np.asarray(lat, float).copy()
    lon_p = lon.copy()
    lon_p[1:][np.abs(np.diff(lon)) > 180] = np.nan  # break the line at the date line
    return lon_p, lat


def fig_ground_track_geometry(s: pd.DataFrame) -> None:
    """500 km, 51.6 deg, RAAN 0: 24 h of ground track around NTU with the
    GMAT-reported contact segments and the 10 deg visibility circle."""
    orbit, label = "h500_i51p6_raan0", "51.6"
    lon_lim, lat_lim = (40, 170), (-60, 60)
    fig, ax = plt.subplots(figsize=(3.5, 3.2))
    t_lo, t_hi = C.WINDOW_OFFSET_H * 3600, (C.WINDOW_OFFSET_H + 24.0) * 3600
    st = gmat_states(orbit)
    t = st["Sat.ElapsedSecs"].values
    day = (t >= t_lo) & (t <= t_hi)
    lon_p, lat_p = track_with_breaks(st["Sat.Earth.Longitude"].values[day], st["Sat.Earth.Latitude"].values[day])
    ax.plot(lon_p, lat_p, color=CATEGORICAL[0], linewidth=0.8)
    passes = window_passes(f"{orbit}_el{MASK:g}")
    passes = passes[(passes.t1 > t_lo) & (passes.t0 < t_hi)]
    for p in passes.itertuples():
        tt = np.concatenate([[p.t0], t[(t > p.t0) & (t < p.t1)], [p.t1]])
        lon = np.interp(tt, t, np.unwrap(np.radians(st["Sat.Earth.Longitude"].values)))
        lat = np.interp(tt, t, st["Sat.Earth.Latitude"].values)
        lo, la = track_with_breaks(np.degrees(lon), lat)
        ax.plot(lo, la, color=CATEGORICAL[1], linewidth=3, solid_capstyle="round")
    mean_alt = row(s, 500, label).mean_alt_km
    clon, clat, lam = visibility_circle(mean_alt, MASK)
    ax.fill(clon, clat, color=CATEGORICAL[1], alpha=0.12, linewidth=0)
    ax.plot(clon, clat, color=CATEGORICAL[1], linewidth=0.8)
    ax.plot(C.STATION_LON_DEG, C.STATION_LAT_DEG, marker="*", markersize=8, color=INK, linestyle="none")
    ax.text(C.STATION_LON_DEG + lam + 1.5, C.STATION_LAT_DEG - 4, "NTU", fontsize=7, va="center")
    ax.set_title(f"500 km, 51.6°, RAAN 0°: first 24 h; thick = contact", loc="left", color=INK_2, fontsize=7)
    ax.set_xlim(*lon_lim)
    ax.set_ylim(*lat_lim)
    ax.set_xticks(range(lon_lim[0], lon_lim[1] + 1, 30))
    ax.set_yticks(range(lat_lim[0], lat_lim[1] + 1, 30))
    ax.set_aspect("equal")
    ax.set_xlabel("Longitude (°E)")
    ax.set_ylabel("Latitude (°)")
    fig.tight_layout()
    save(fig, "fig_ground_track_geometry")
    # circle radius for the 0 deg orbit is quoted in the report (Section 5)
    check("LamFive", visibility_circle(row(s, 500, "0").mean_alt_km, MASK)[2], "{:.1f}")
    CHECKS.append(f"ground track 51.6 deg: {len(passes)} GMAT passes touch the first 24 h")


