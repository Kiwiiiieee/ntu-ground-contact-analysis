# ----------------------------------------------------------------------------- data + checks
def load_summary() -> pd.DataFrame:
    s = pd.read_csv(ROOT / "results" / "contact_summary.csv")
    s["orbit_label"] = s["orbit_label"].map(lambda v: f"{float(v):g}" if v != "SSO" else "SSO")
    return s


def load_numbers() -> dict[str, str]:
    """Macros from report/numbers.tex: name -> formatted value."""
    text = NUMBERS.read_text(encoding="utf-8")
    return dict(re.findall(r"\\newcommand\{\\(\w+)\}\{(.*)\}", text))


NUM = load_numbers()
CHECKS: list[str] = []


def check(macro: str, value, fmt: str) -> None:
    """The plotted value, formatted as in the report, must equal numbers.tex."""
    got = fmt.format(value)
    if NUM.get(macro) != got:
        sys.exit(f"MISMATCH with numbers.tex: \\{macro} = {NUM.get(macro)!r}, figure data give {got!r}")
    CHECKS.append(f"\\{macro} = {got}")


def row(s, h, lab, mask=MASK):
    r = s[(s.nominal_altitude_km == h) & (s.orbit_label == lab) & (s.elevation_mask_deg == mask)]
    assert len(r) == 1
    return r.iloc[0]


def save(fig, name: str) -> None:
    for ext in ("pdf", "png"):
        fig.savefig(FIG / f"{name}.{ext}")
    plt.close(fig)
    print(f"figures/{name}.pdf, .png")


def gmat_states(orbit_name: str) -> pd.DataFrame:
    path = REF / f"{orbit_name}_states.txt"
    if not path.exists():
        sys.exit(f"missing {path}: run `uv run src/gmat_reference.py` first")
    return pd.read_csv(path, sep=r"\s+")


def elevation_deg(states: pd.DataFrame) -> np.ndarray:
    """Elevation at NTU from GMAT's Earth-fixed positions, using the same station
    geometry as the cross-check (ellipsoid normal; checked equal to GMAT's
    topocentric declination to 5e-8 deg)."""
    import crosscheck as X                       # station position and local up
    r = states[["Sat.EarthFixed.X", "Sat.EarthFixed.Y", "Sat.EarthFixed.Z"]].values.T
    rho = r - X.STATION[:, None]
    return np.degrees(np.arcsin(X.UP @ rho / np.linalg.norm(rho, axis=0)))


def window_passes(report_name: str) -> pd.DataFrame:
    """Passes touching the analysis window, with seconds since the epoch."""
    p = P.classify(P.read_report(RAW / f"{report_name}.txt"))
    p = p[p.in_window].copy()
    p["t0"] = (p.start - P.EPOCH).dt.total_seconds()
    p["t1"] = (p.stop - P.EPOCH).dt.total_seconds()
    return p


# ----------------------------------------------------------------------------- heatmap
def fig_contact_heatmap(s: pd.DataFrame) -> None:
    d = s[s.elevation_mask_deg == MASK]
    table = d.pivot(index="orbit_label", columns="nominal_altitude_km", values="mean_contact_min_per_day").loc[INC_ORDER]
    cmap = LinearSegmentedColormap.from_list("blue_seq", BLUE_RAMP)
    fig, ax = plt.subplots(figsize=(3.0, 2.75))     # printed at this size (body, left)
    im = ax.imshow(table.values, cmap=cmap, aspect="auto", vmin=0)
    ax.grid(False)
    # White separators: each cell is one simulated case, nothing in between.
    ax.set_xticks(np.arange(-0.5, table.shape[1]), minor=True)
    ax.set_yticks(np.arange(-0.5, table.shape[0]), minor=True)
    ax.grid(which="minor", color="white", linewidth=2.5)
    ax.tick_params(which="minor", length=0)
    ax.set_xticks(range(table.shape[1]), [f"{h:g}" for h in table.columns])
    ax.set_yticks(range(table.shape[0]), [INC_NAME[c].replace(" (", "\n(") for c in table.index])
    ax.set_xlabel("Nominal altitude (km)")
    ax.set_ylabel("Inclination")
    vmax = np.nanmax(table.values)
    for i in range(table.shape[0]):
        for j in range(table.shape[1]):
            v = table.values[i, j]
            ax.text(j, i, f"{v:.0f}", ha="center", va="center", fontsize=6.5, color="white" if v > 0.55 * vmax else INK)
    for side in ("left", "bottom"):
        ax.spines[side].set_visible(False)
    cb = fig.colorbar(im, ax=ax, pad=0.02)
    cb.set_label("Contact time (min/day)")
    cb.outline.set_visible(False)
    cb.ax.tick_params(colors=INK_2)
    fig.tight_layout()
    save(fig, "fig_contact_heatmap")
    check("CZeroLo", table.loc["0", 400], "{:.1f}")
    check("CZeroHi", table.loc["0", 800], "{:.1f}")
    check("HiCMin", table.loc[["45", "51.6", "SSO"]].values.min(), "{:.1f}")
    check("HiCMax", table.loc[["45", "51.6", "SSO"]].values.max(), "{:.1f}")


# ----------------------------------------------------------------------------- contact vs altitude
def fig_contact_vs_altitude(s: pd.DataFrame) -> None:
    """Means at the true nominal altitudes; band = min-max over the RAAN runs.

    Two rows: low inclinations (0-20 deg) and high inclinations (45 deg,
    51.6 deg, SSO) on their own y-scale, because at one scale the three
    high-inclination bands overlap into an unreadable strip.
    """
    groups = [["0", "10", "20"], ["45", "51.6", "SSO"]]
    fig, axes = plt.subplots(2, 2, figsize=(4.0, 2.75), sharex=True)   # printed at this size (body, right)
    for col, mask in enumerate(C.MASKS_DEG):
        d = s[s.elevation_mask_deg == mask]
        for r, labels in enumerate(groups):
            ax = axes[r, col]
            for label in labels:
                k = INC_ORDER.index(label)
                g = d[d.orbit_label == label].sort_values("nominal_altitude_km")
                ax.fill_between(g.nominal_altitude_km, g.min_contact_min_per_day, g.max_contact_min_per_day,
                                color=CATEGORICAL[k], alpha=0.22, linewidth=0)
                ax.plot(g.nominal_altitude_km, g.mean_contact_min_per_day, color=CATEGORICAL[k],
                        marker=MARKERS[k], label=INC_NAME[label], linewidth=1.2, markersize=3)
            ax.set_ylim(bottom=0)
            ax.set_xticks(C.ALTITUDES_KM)
            ax.tick_params(labelsize=6)
            if r == 0:
                ax.set_title(f"{mask:g}° mask", loc="left", color=INK_2, fontsize=7)
            if col == 0:
                ax.set_ylabel("Contact (min/day)", fontsize=7)
                ax.legend(loc="upper left", fontsize=5.5, handlelength=1.6, borderaxespad=0.2, labelspacing=0.25)
            if r == 1:
                ax.set_xlabel("Nominal altitude (km)", fontsize=7)
    # share y within a row so the two masks are directly comparable; the top
    # row is tightened to the data (incl. RAAN bands), the bottom row starts at 0
    for r, labels in enumerate(groups):
        sel = s[s.orbit_label.isin(labels)]
        lo, hi = sel.min_contact_min_per_day.min(), sel.max_contact_min_per_day.max()
        lims = (10 * math.floor(lo / 10) - 10, 10 * math.ceil(hi / 10) + 20) if r == 0 else (0, hi * 1.25)
        for col in range(2):
            axes[r, col].set_ylim(*lims)
    fig.tight_layout()
    save(fig, "fig_contact_vs_altitude")
    for lab, key in [("0", "Zero"), ("45", "Ff")]:
        check(f"Mask{key}B", row(s, 500, lab, 5).mean_contact_min_per_day, "{:.1f}")
        check(f"Mask{key}C", row(s, 700, lab, 10).mean_contact_min_per_day, "{:.1f}")
    check("RaanCMin", row(s, 500, "45").min_contact_min_per_day, "{:.1f}")
    check("RaanCMax", row(s, 500, "45").max_contact_min_per_day, "{:.1f}")


