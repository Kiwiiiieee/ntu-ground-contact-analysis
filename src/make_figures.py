def peak_elevation(t, el, t0, t1) -> float:
    """Maximum elevation in [t0, t1]: largest 60 s sample, refined by a parabola
    through it and its neighbours."""
    inside = np.where((t >= t0) & (t <= t1))[0]
    i = inside[np.argmax(el[inside])]
    if 0 < i < len(t) - 1:
        y0, y1, y2 = el[i - 1], el[i], el[i + 1]
        den = y0 - 2 * y1 + y2
        if den < 0:
            return y1 - (y0 - y2) ** 2 / (8 * den)
    return el[i]


def fig_gmat_python_validation() -> None:
    ev = pd.read_csv(ROOT / "results" / "crosscheck" / "comparison_events.csv", parse_dates=["gmat_start"])
    ev["orbit"] = ev.case_id.str.rsplit("_el", n=1).str[0]
    ev["mask"] = ev.case_id.str.rsplit("_el", n=1).str[1].astype(float)
    peaks = []
    for orbit, g in ev.groupby("orbit", sort=False):
        st = gmat_states(orbit)
        t, el = st["Sat.ElapsedSecs"].values, elevation_deg(st)
        t0 = (g.gmat_start - P.EPOCH).dt.total_seconds().values
        peaks.append(pd.Series([peak_elevation(t, el, a, a + d) for a, d in zip(t0, g.gmat_duration_s)], index=g.index))
    ev["peak_el"] = pd.concat(peaks)
    res = np.concatenate([ev.d_start_s, ev.d_stop_s]) * 1e3
    # Peak elevations are saved so the report's numbers can be generated from them.
    ev[["case_id", "gmat_start", "peak_el", "d_start_s", "d_stop_s"]].to_csv(
        ROOT / "results" / "crosscheck" / "pass_peak_elevations.csv", index=False, float_format="%.6f")
    fig, (a, b) = plt.subplots(1, 2, figsize=(7.0, 2.6), gridspec_kw={"width_ratios": [1, 1]})
    labels = {o: f"{o.split('_')[0][1:]} km, {o.split('_')[1][1:].replace('p', '.')}" + ("°" if "SSO" not in o else "")
              for o in ev.orbit.unique()}
    # (A) Position difference vs time, recomputed exactly as compare_crosscheck.py does
    pydir = ROOT / "results" / "crosscheck" / "python"
    max_in, max_fx = 0.0, 0.0
    for k, orbit in enumerate(ev.orbit.unique()):
        g_st = gmat_states(orbit)
        py = np.load(pydir / f"{orbit}_states.npz")
        idx = np.rint(g_st["Sat.ElapsedSecs"].values / 60.0).astype(int)
        d_in = np.linalg.norm(py["r_gcrs"][:, idx] - g_st[[f"Sat.EarthMJ2000Eq.{c}" for c in "XYZ"]].values.T, axis=0)
        d_fx = np.linalg.norm(py["r_itrs"][:, idx] - g_st[[f"Sat.EarthFixed.{c}" for c in "XYZ"]].values.T, axis=0)
        # The difference oscillates within every orbit; plot its maximum over
        # consecutive 100-min intervals (~one orbit), an envelope, not a smoothing.
        days = g_st["Sat.ElapsedSecs"].values / 86400
        n = 100                                            # 100 samples of 60 s
        m = len(days) // n * n
        env = lambda d: d[:m].reshape(-1, n).max(axis=1)
        mid = days[:m].reshape(-1, n).mean(axis=1)
        a.plot(mid, env(d_in) * 1e3, color=CATEGORICAL[k], linewidth=1.2, label=labels[orbit])
        a.plot(mid, env(d_fx) * 1e3, color=CATEGORICAL[k], linewidth=0.9, linestyle="--")
        max_in, max_fx = max(max_in, d_in.max()), max(max_fx, d_fx.max())
    a.set_xlabel("Days since epoch")
    a.set_ylabel("Max |Python − GMAT| per 100 min (m)")
    a.set_title("(A) position difference: solid inertial, dashed Earth-fixed", loc="left", color=INK_2, fontsize=7)
    a.legend(loc="upper left", fontsize=6, handlelength=1.5)
    a.set_ylim(bottom=0)
    check("TrajInertialM", 1000 * max_in, "{:.0f}")
    check("TrajFixedM", 1000 * max_fx, "{:.0f}")
    # (B) pass timing residual vs peak elevation
    for k, (orbit, g) in enumerate(ev.groupby("orbit", sort=False)):
        b.scatter(g.peak_el, g.d_start_s * 1e3, s=6, marker="o", color=CATEGORICAL[k], linewidths=0)
        b.scatter(g.peak_el, g.d_stop_s * 1e3, s=7, marker="x", color=CATEGORICAL[k], linewidths=0.7)
    b.axhline(0, color=AXIS, linewidth=0.8)
    b.set_ylabel("Python − GMAT (ms)")
    b.set_xlabel("Peak elevation of the pass (°)")
    rms = np.sqrt(np.mean(res**2))
    b.set_title("(B) pass start (o) and stop (x) residuals", loc="left", color=INK_2, fontsize=7)
    lim = np.abs(res).max() * 1.25
    b.set_ylim(-lim, lim)
    fig.tight_layout()
    save(fig, "fig_gmat_python_validation")
    check("NMatched", len(ev), "{:d}")
    check("MaxDtMs", np.abs(res).max(), "{:.1f}")
    # Report the structure seen in panel B for the write-up (no claim made in code).
    corr = np.corrcoef(np.concatenate([ev.peak_el, ev.peak_el]), np.abs(res))[0, 1]
    # The appendix caption says the largest residuals occur on low passes.
    if not corr < 0:
        sys.exit(f"CLAIM NO LONGER SUPPORTED: |residual| does not decrease with peak elevation (corr {corr:+.2f})")
    check("ResRmsMs", rms, "{:.1f}")
    CHECKS.append(f"validation: RMS {rms:.2f} ms; corr(|residual|, peak elevation) = {corr:+.2f}; "
                  f"mean start residual {ev.d_start_s.mean()*1e3:+.2f} ms, mean stop residual {ev.d_stop_s.mean()*1e3:+.2f} ms")


# ----------------------------------------------------------------------------- RAAN sensitivity
def fig_raan_sensitivity(s: pd.DataFrame) -> None:
    runs = pd.read_csv(ROOT / "results" / "contact_runs.csv")
    alt, lab = 500, "45"
    g = runs[(runs.nominal_altitude_km == alt) & (runs.orbit_label.astype(str) == lab)
             & (runs.elevation_mask_deg == MASK)].sort_values("raan_deg")
    assert len(g) == len(C.RAAN_SAMPLES_DEG)
    metrics = [("contact_min_per_day", "Contact\n(min/day)"), ("passes_per_day", "Passes/day"),
               ("longest_gap_h", "Longest\ngap (h)")]
    fig, axes = plt.subplots(3, 1, figsize=(3.5, 3.0), sharex=True)
    for ax, (col, ylab) in zip(axes, metrics):
        ax.plot(g.raan_deg, g[col], color=CATEGORICAL[3], marker="D", linewidth=0.8)
        mean = g[col].mean()
        ax.axhline(mean, color=INK_2, linewidth=0.9, linestyle="--")
        ax.text(1.0, mean, " 8-RAAN mean", transform=ax.get_yaxis_transform(), va="center", fontsize=6, color=INK_2)
        ax.set_ylabel(ylab)
        if col == "contact_min_per_day":
            check("RaanCMin", g[col].min(), "{:.1f}")
            check("RaanCMax", g[col].max(), "{:.1f}")
            if abs(mean - row(s, alt, lab).mean_contact_min_per_day) > 1e-3:
                sys.exit("MISMATCH: RAAN mean contact vs contact_summary.csv")
        if col == "passes_per_day":
            check("RaanPMin", g[col].min(), "{:.2f}")
            check("RaanPMax", g[col].max(), "{:.2f}")
    axes[-1].set_xticks(C.RAAN_SAMPLES_DEG)
    axes[-1].set_xlabel("Starting RAAN (°)")
    axes[0].set_title(f"{alt} km, {lab}°, {MASK:g}° mask: each point is one 7-day run", loc="left", color=INK_2)
    fig.tight_layout()
    save(fig, "fig_raan_sensitivity")


# ----------------------------------------------------------------------------- schematic
def fig_visibility_geometry() -> None:
    """Cross-section through Earth's centre O, station S and satellite P at the
    moment it crosses the mask. Not to scale (altitude exaggerated)."""
    R, r = 1.0, 1.55                                   # schematic radii
    e = math.radians(12.0)                             # drawn mask angle (schematic)
    lam = math.acos(R * math.cos(e) / r) - e           # same relation as in the report
    fig, ax = plt.subplots(figsize=(3.5, 3.0))
    ax.set_aspect("equal")
    ax.axis("off")
    th = np.linspace(math.radians(40), math.radians(140), 200)
    ax.plot(R * np.cos(th), R * np.sin(th), color=INK_2, linewidth=1.2)
    ax.plot(r * np.cos(th), r * np.sin(th), color=AXIS, linewidth=0.9, linestyle="--")
    ax.text(r * math.cos(th[-12]), r * math.sin(th[-12]) + 0.04, "orbit (radius r)", fontsize=6.5, color=INK_2, ha="center")
    ax.text(R * math.cos(th[-25]) - 0.05, R * math.sin(th[-25]) - 0.1, "Earth (R)", fontsize=6.5, color=INK_2)
    S = np.array([0.0, R])                             # station at the top
    ang_p = math.pi / 2 - lam                          # satellite, central angle lam from S
    Pp = r * np.array([math.cos(ang_p), math.sin(ang_p)])
    O = np.array([0.0, 0.0])
    ax.plot(*O, "o", color=INK, markersize=3)
    ax.text(0.03, -0.02, "O", fontsize=7, va="top")
    ax.plot([0, 0], [0, R], color=INK_2, linewidth=0.8)
    ax.plot([0, Pp[0]], [0, Pp[1]], color=INK_2, linewidth=0.8)
    ax.plot([-0.55, 0.75], [R, R], color=MUTED, linewidth=0.9)            # local horizon (tangent plane)
    ax.text(-0.55, R + 0.02, "local horizon", fontsize=6.5, color=MUTED)
    ax.plot([S[0], Pp[0]], [S[1], Pp[1]], color=CATEGORICAL[1], linewidth=1.4)   # line of sight at the mask
    ax.plot(*S, marker="^", color=INK, markersize=7)
    ax.text(S[0] - 0.06, S[1] + 0.13, "S (NTU)", fontsize=7, ha="right")
    ax.plot(*Pp, "o", color=CATEGORICAL[0], markersize=6)
    ax.text(Pp[0] + 0.05, Pp[1], "P (satellite)", fontsize=7, va="center")
    ax.add_patch(Arc(S, 0.5, 0.5, theta1=0, theta2=math.degrees(e), color=CATEGORICAL[1], linewidth=1))
    ax.text(S[0] + 0.27, S[1] - 0.09, "$e_{\\min}$", fontsize=8, color=CATEGORICAL[1])
    ax.add_patch(Arc(O, 0.45, 0.45, theta1=math.degrees(ang_p), theta2=90, color=INK, linewidth=1))
    ax.text(0.07, 0.27, "$\\lambda$", fontsize=9)
    ax.annotate("", xy=(0, R + 0.32), xytext=(0, R), arrowprops=dict(arrowstyle="->", color=INK_2, lw=0.8))
    ax.text(0.03, R + 0.3, "$\\hat{\\mathbf{u}}$ (up)", fontsize=7, color=INK_2)
    ax.text(0.42, 0.02, "visible  $\\Leftrightarrow$  $e \\geq e_{\\min}$\n"
            "$\\lambda=\\arccos(R\\cos e_{\\min}/r)-e_{\\min}$\nnot to scale", fontsize=6.5, color=INK_2, va="bottom")
    ax.set_xlim(-1.0, 1.25)
    ax.set_ylim(-0.05, 1.75)
    save(fig, "fig_visibility_geometry")


